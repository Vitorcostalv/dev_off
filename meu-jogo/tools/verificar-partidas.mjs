import assert from 'node:assert/strict';
import { createDefaultSave } from '../src/game/SaveMigration.ts';
import { salvar } from '../src/game/save.ts';
import { listarPartidas, guardarPartida, carregarPartida, descreverPartida } from '../src/game/partidas.ts';
const memoria = new Map(); let falhar = '';
globalThis.localStorage = { getItem: k => memoria.get(k) ?? null, setItem: (k, v) => { if (k === falhar) throw Error('quota'); memoria.set(k, v); }, removeItem: k => memoria.delete(k) };
assert.equal(listarPartidas().length, 6);
assert(listarPartidas().every(p => p.estado === 'vazio'));
const base = createDefaultSave();
assert(salvar({ ...base, dia: 62, minutos: 1112, worldEvents: { flags: { 'sessao:segundos': 3720 }, falasVistas: [] } }));
const auto = listarPartidas()[0];
assert.equal(auto.data, 'Outono — Ano 1'); assert.equal(auto.tempo, '1h 2min'); assert(auto.hora.endsWith('18:32'));
for (const id of ['1', '2', '3', '4']) assert(guardarPartida(id));
assert(!guardarPartida('auto')); assert(!guardarPartida('__proto__'));
assert(salvar({ ...base, dia: 90 }));
assert.equal(listarPartidas().find(p => p.id === '1').dados.dia, 62);
assert(carregarPartida('1')); assert.equal(listarPartidas()[0].dados.dia, 62);
assert.equal(listarPartidas().at(-1).dados.dia, 90);
falhar = 'meu-jogo:partida:1';
const antes = memoria.get(falhar); assert(!guardarPartida('1')); assert.equal(memoria.get(falhar), antes);
falhar = 'meu-jogo:save'; assert(!carregarPartida('2')); assert.equal(listarPartidas()[0].dados.dia, 62);
falhar = '';
assert.equal(descreverPartida('', '', '{').estado, 'danificado');
assert.equal(descreverPartida('', '', '{}').estado, 'danificado');
assert.equal(descreverPartida('', '', JSON.stringify({ ...base, versao: 999 })).estado, 'incompativel');
assert.equal(descreverPartida('', '', JSON.stringify({ ...base, versao: 6 })).estado, 'disponivel');
memoria.set('meu-jogo:partida:3', JSON.stringify({ ...base, versao: 999 }));
assert(!carregarPartida('3'));
assert.equal(listarPartidas()[0].dados.dia, 62);
console.log('Partidas: quatro espaços, autosave, backup, metadados, migração, incompatibilidade e falhas de escrita passaram.');
